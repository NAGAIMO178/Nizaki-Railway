const STOP = '2331112';
const START_B = 104;

export const CODE128_PATTERNS = PATTERNS;
export const CODE128_STOP = STOP;

export interface Code128 {
  bars: number[]; // バー・スペースの幅(モジュール数)。最初はバー
  modules: number; // 合計のモジュール数(左右の余白は含まない)
}

// 文字列 → バーとスペースの幅。使えない文字があれば例外
export const encodeCode128B = (text: string): Code128 => {
  const values: number[] = [START_B];
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code < 32 || code > 126) throw new Error('Code128-B で表せない文字です');
    values.push(code - 32);
  }
  let sum = START_B;
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103);
  const bars = [...values.map((v) => PATTERNS[v]), STOP].join('').split('').map(Number);
  return { bars, modules: bars.reduce((a, b) => a + b, 0) };
};

// 左右に必要な白い余白(モジュール数)
export const CODE128_QUIET = 10;

// バーを塗る。fill は (x, y, 幅, 高さ) で長方形を塗る関数(画面の canvas でも、確かめるときの画素でも使える)
export const paintCode128 = (
  fill: (x: number, y: number, w: number, h: number) => void,
  code: Code128,
  x: number,
  y: number,
  unit: number,
  height: number,
) => {
  let cursor = x;
  code.bars.forEach((width, i) => {
    if (i % 2 === 0) fill(cursor, y, width * unit, height);
    cursor += width * unit;
  });
};
