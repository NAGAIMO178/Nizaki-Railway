// マイページの「ログアウトの確認」に出す説明。端末に残るもの・戻るものが、実際の動きと合うように、条件で変える。
//  - synced = true: サーバーに同期ずみのクラウドの会員。ログアウトで、端末の控え(ポイント・履歴)が消え、ログインし直すと、サーバーから戻る
//    (いまの予約の控えは、ログアウトでも残る: src/utils/memberData.ts)
//  - synced = false: 同期の前・公開前(端末だけで持っている会員)。端末内のポイントなどは残るので、これまでの説明のまま
export const logoutNoticeText = (synced: boolean, balance: number, email: string): string =>
  synced
    ? 'ログアウトすると、この端末に保存されているN-POINTや履歴の控えは消えます。もう一度ログインすると、サーバーから続きが戻ります（別の端末でも同じです）。いまの予約は、ログアウトしても残ります。'
    : `ログアウトしても、この端末に保存されているN-POINT（${balance.toLocaleString()}pt）や予約の記録は残ります。同じ端末で同じメールアドレス（${email}）でログインすると続きから使えます。なお、これらの記録は端末ごとに保存されるため、別の端末には引き継がれません。`;
